#!/usr/bin/env node
/**
 * Download @imgly/background-removal-data 1.7.0 and keep only
 * isnet_quint8 + ONNX Runtime WASM (CPU + WebGPU/jsep) under public/bg-removal/.
 * Full package is ~328MB; pruned set is ~80MB.
 *
 * Chunk files are stored with a `.bin` suffix. Capacitor Android's WebViewLocalServer
 * html5mode treats extensionless paths as SPA routes and returns index.html — bare
 * hash names therefore never load. The `name` field in resources.json must match the
 * on-disk filename (hash + .bin); `hash` stays the original content hash.
 *
 * resources.json is committed so Vite/Capacitor know the asset map, but the
 * large chunk files are gitignored. Skip only when every listed chunk exists.
 */
import {
  createWriteStream,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
  readFileSync,
  copyFileSync,
} from 'node:fs'
import { pipeline } from 'node:stream/promises'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const VERSION = '1.7.0'
const SRC = `https://staticimgly.com/@imgly/background-removal-data/${VERSION}/package.tgz`
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'public', 'bg-removal')
const TMP = path.join(ROOT, '.tmp-bg-removal')

/** Capacitor serves only paths whose last segment contains `.`; use .bin for all chunks. */
const CHUNK_EXT = '.bin'

const KEEP_KEYS = [
  '/models/isnet_quint8',
  '/onnxruntime-web/ort-wasm-simd-threaded.wasm',
  '/onnxruntime-web/ort-wasm-simd-threaded.mjs',
  '/onnxruntime-web/ort-wasm-simd-threaded.jsep.wasm',
  '/onnxruntime-web/ort-wasm-simd-threaded.jsep.mjs',
]

function toDiskName(rawName) {
  if (!rawName) return rawName
  return rawName.includes('.') ? rawName : `${rawName}${CHUNK_EXT}`
}

function rewriteEntry(entry) {
  if (!entry?.chunks) return entry
  return {
    ...entry,
    chunks: entry.chunks.map((c) => ({
      ...c,
      name: toDiskName(c.name),
    })),
  }
}

function chunkNamesFromResources(resources) {
  const need = new Set()
  for (const key of KEEP_KEYS) {
    const entry = resources[key]
    if (!entry) continue
    for (const c of entry.chunks || []) need.add(c.name)
  }
  return need
}

function assetsComplete() {
  const resourcesPath = path.join(OUT, 'resources.json')
  if (!existsSync(resourcesPath)) return false
  let resources
  try {
    resources = JSON.parse(readFileSync(resourcesPath, 'utf8'))
  } catch {
    return false
  }
  if (!resources['/models/isnet_quint8']) return false
  const need = chunkNamesFromResources(resources)
  if (need.size === 0) return false
  for (const name of need) {
    // Reject legacy extensionless layout — Capacitor cannot serve those.
    if (!name.includes('.')) return false
    if (!existsSync(path.join(OUT, name))) return false
  }
  return true
}

async function main() {
  if (process.env.FORCE !== '1' && assetsComplete()) {
    console.log('public/bg-removal already complete (set FORCE=1 to re-download)')
    return
  }

  rmSync(TMP, { recursive: true, force: true })
  mkdirSync(TMP, { recursive: true })
  const tgz = path.join(TMP, 'package.tgz')
  console.log('Downloading', SRC)
  const res = await fetch(SRC)
  if (!res.ok) throw new Error(`download failed: ${res.status}`)
  await pipeline(res.body, createWriteStream(tgz))
  console.log('Extracting…')
  execFileSync('tar', ['-xzf', tgz, '-C', TMP])
  const dist = path.join(TMP, 'package', 'dist')
  const resources = JSON.parse(readFileSync(path.join(dist, 'resources.json'), 'utf8'))
  const pruned = {}
  const needRaw = new Set()
  for (const key of KEEP_KEYS) {
    if (!resources[key]) {
      console.warn('missing key', key)
      continue
    }
    pruned[key] = rewriteEntry(resources[key])
    for (const c of resources[key].chunks || []) needRaw.add(c.name)
  }

  // Keep committed README / .gitkeep; replace everything else.
  if (existsSync(OUT)) {
    for (const name of readdirSync(OUT)) {
      if (name === 'README.md' || name === '.gitkeep') continue
      rmSync(path.join(OUT, name), { recursive: true, force: true })
    }
  }
  mkdirSync(OUT, { recursive: true })
  writeFileSync(path.join(OUT, 'resources.json'), JSON.stringify(pruned, null, 2))
  let bytes = 0
  for (const raw of needRaw) {
    const from = path.join(dist, raw)
    if (!existsSync(from)) throw new Error(`chunk missing: ${raw}`)
    const diskName = toDiskName(raw)
    copyFileSync(from, path.join(OUT, diskName))
    bytes += Number(execFileSync('stat', ['-c%s', from]).toString())
  }
  if (!existsSync(path.join(OUT, 'README.md'))) {
    writeFileSync(
      path.join(OUT, 'README.md'),
      `# Self-hosted @imgly/background-removal-data ${VERSION} (pruned)\n\nOnly \`isnet_quint8\` + ONNX Runtime WASM. Generated by \`npm run fetch:bg-removal\`.\nChunks use a \`.bin\` suffix so Capacitor Android html5mode does not treat them as SPA routes.\nDo not commit large chunks if repo size is a concern — CI/deploy fetches them.\n`,
    )
  }
  console.log(`Wrote ${needRaw.size} chunks (.bin) + resources.json (~${(bytes / 1e6).toFixed(1)} MB) → ${OUT}`)
  rmSync(TMP, { recursive: true, force: true })
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
