#!/usr/bin/env node
/**
 * Download @imgly/background-removal-data 1.7.0 and keep only
 * isnet_quint8 + ONNX Runtime WASM (CPU + WebGPU/jsep) under public/bg-removal/.
 * Full package is ~328MB; pruned set is ~80MB.
 */
import { createWriteStream, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync, readFileSync, copyFileSync } from 'node:fs'
import { pipeline } from 'node:stream/promises'
import { createGunzip } from 'node:zlib'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const VERSION = '1.7.0'
const SRC = `https://staticimgly.com/@imgly/background-removal-data/${VERSION}/package.tgz`
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'public', 'bg-removal')
const TMP = path.join(ROOT, '.tmp-bg-removal')

const KEEP_KEYS = [
  '/models/isnet_quint8',
  '/onnxruntime-web/ort-wasm-simd-threaded.wasm',
  '/onnxruntime-web/ort-wasm-simd-threaded.mjs',
  '/onnxruntime-web/ort-wasm-simd-threaded.jsep.wasm',
  '/onnxruntime-web/ort-wasm-simd-threaded.jsep.mjs',
]

async function main() {
  if (existsSync(path.join(OUT, 'resources.json')) && process.env.FORCE !== '1') {
    const st = readFileSync(path.join(OUT, 'resources.json'), 'utf8')
    if (st.includes('isnet_quint8')) {
      console.log('public/bg-removal already present (set FORCE=1 to re-download)')
      return
    }
  }

  rmSync(TMP, { recursive: true, force: true })
  mkdirSync(TMP, { recursive: true })
  const tgz = path.join(TMP, 'package.tgz')
  console.log('Downloading', SRC)
  const res = await fetch(SRC)
  if (!res.ok) throw new Error(`download failed: ${res.status}`)
  await pipeline(res.body, createWriteStream(tgz))
  console.log('Extracting…')
  execFileSync('tar', ['-xzf', tgz, '-C', TMP])
  const dist = path.join(TMP, 'package', 'dist')
  const resources = JSON.parse(readFileSync(path.join(dist, 'resources.json'), 'utf8'))
  const pruned = {}
  const need = new Set()
  for (const key of KEEP_KEYS) {
    if (!resources[key]) {
      console.warn('missing key', key)
      continue
    }
    pruned[key] = resources[key]
    for (const c of resources[key].chunks || []) need.add(c.name)
  }

  rmSync(OUT, { recursive: true, force: true })
  mkdirSync(OUT, { recursive: true })
  writeFileSync(path.join(OUT, 'resources.json'), JSON.stringify(pruned, null, 2))
  let bytes = 0
  for (const name of need) {
    const from = path.join(dist, name)
    if (!existsSync(from)) throw new Error(`chunk missing: ${name}`)
    copyFileSync(from, path.join(OUT, name))
    bytes += Number(execFileSync('stat', ['-c%s', from]).toString())
  }
  // license note
  writeFileSync(
    path.join(OUT, 'README.md'),
    `# Self-hosted @imgly/background-removal-data ${VERSION} (pruned)\n\nOnly \`isnet_quint8\` + ONNX Runtime WASM. Generated by \`npm run fetch:bg-removal\`.\nDo not commit large chunks if repo size is a concern — CI/deploy fetches them.\n`,
  )
  console.log(`Wrote ${need.size} chunks + resources.json (~${(bytes / 1e6).toFixed(1)} MB) → ${OUT}`)
  rmSync(TMP, { recursive: true, force: true })
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
